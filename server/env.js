'use strict';

// Minimal .env loader — zero-dependency substitute for dotenv.
// Supports KEY=VALUE lines, '#' comments, blank lines, and optional
// single/double quotes around values. No variable interpolation.
// Real environment variables always win: .env only fills gaps.

const fs = require('node:fs');
const path = require('node:path');

function load(file = path.join(__dirname, '..', '.env')) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    return; // no .env file — fine, env vars may come from the shell
  }
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

module.exports = { load };
